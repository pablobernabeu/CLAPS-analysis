#!/usr/bin/env Rscript
# scripts/build_registered_arc_check.R
# ---------------------------------------------------------------------------
# Check, in the environment of record, that scripts/run_klanguage_registered.R
# reproduces the reported klanguage_registered.csv, without writing anything there.
#
# The K-language tables are computed on a workstation (docs/reproducibility.md). This
# script carries the check to ARC's R 4.4.2. "build" writes a self-contained R program
# that holds the engine, the registered script and the small input tables as text, and
# reads the pilot extracts from a directory given on ARC, whose checksums should match
# config/pilot_models_sha256.csv. The program prints its table between markers instead
# of writing it, and it opens no log. The registered script re-creates six reported
# cells of klanguage_known7.csv and klanguage_pseudo_passive.csv on the way, so one run
# checks those too. "compare" reads the console output and compares the table with the
# reported one, line by line.
#
# Run from design_analysis/:
#   Rscript scripts/build_registered_arc_check.R build <check.R>
#   ssh <arc-host> 'bash -lc "module load R/4.4.2-gfbf-2024a;
#     export R_LIBS_USER=$DATA/PROJECT_GROUP/R/library_4.4; cd /tmp;
#     R --no-echo --vanilla --args --outdir=/nonexistent
#       --pilot-models=$DATA/PROJECT_GROUP/outputs/pilot_models"' < <check.R> > <arc_output.txt>
#   Rscript scripts/build_registered_arc_check.R compare <arc_output.txt>
# ---------------------------------------------------------------------------

args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2L || !args[1] %in% c("build", "compare")) {
  stop("usage: build_registered_arc_check.R build <check.R> | compare <arc_output.txt>")
}
REPORTED <- "outputs/design_summary_pilot/klanguage_registered.csv"

if (args[1] == "build") {
  files <- c("R/13_simulate_klanguage_pooled.R",
             "scripts/run_klanguage_registered.R",
             "outputs/design_summary_pilot/cross_language_effects_harmonised.csv",
             "outputs/design_summary_pilot/pilot_params_ceilings.csv",
             "outputs/design_summary_pilot/klanguage_known7.csv",
             "outputs/design_summary_pilot/klanguage_pseudo_passive.csv",
             "config/prior_grid.yaml")
  # Each file travels as an R raw string, so it needs a closing delimiter it never contains.
  open_delim <- 'r"-----['
  close_delim <- ']-----"'
  text <- vapply(files, function(f) {
    x <- paste(readLines(f, warn = FALSE, encoding = "UTF-8"), collapse = "\n")
    if (grepl(close_delim, x, fixed = TRUE)) stop("the raw-string delimiter occurs in ", f)
    x
  }, character(1))
  program <- c(
    "# Generated by scripts/build_registered_arc_check.R. Writes nothing; prints its table.",
    "EMB <- list()",
    sprintf("EMB[[%s]] <- %s%s%s", vapply(files, deparse, character(1)), open_delim, text, close_delim),
    paste0("LOCAL_MD5 <- ", paste(deparse(tools::md5sum(files)), collapse = "")),
    "cat('embedded files, md5 of the copies they were built from:\\n')",
    "print(LOCAL_MD5)",
    "read.csv <- function(file, ...) {",
    "  if (file %in% names(EMB)) utils::read.csv(text = EMB[[file]], ...) else utils::read.csv(file, ...)",
    "}",
    "write.csv <- function(x, file, ...) {",
    "  cat('<<<CSV ', basename(file), '\\n', sep = '')",
    "  utils::write.csv(x, stdout(), ...)",
    "  cat('CSV>>>\\n')",
    "}",
    "dir.create <- function(...) invisible(TRUE)",
    "utils::assignInNamespace('read_yaml', function(file, ...) yaml::yaml.load(EMB[[file]], ...), ns = 'yaml')",
    "source <- function(file, ...) {",
    "  eval(parse(text = EMB[[file]], keep.source = FALSE), envir = globalenv())",
    "  if (identical(file, 'R/13_simulate_klanguage_pooled.R')) {",
    "    assign('start_run_log', function(log_path, inputs = character(0), ...) {",
    "      cat('R:', R.version.string, '\\n')",
    "      invisible(NULL)",
    "    }, envir = globalenv())",
    "    assign('stop_run_log', function(con) invisible(NULL), envir = globalenv())",
    "    assign('guard_reported_dir', function(out, args, ...) invisible(FALSE), envir = globalenv())",
    "  }",
    "  invisible(NULL)",
    "}",
    "eval(parse(text = EMB[['scripts/run_klanguage_registered.R']], keep.source = FALSE), envir = globalenv())"
  )
  writeLines(program, args[2], useBytes = TRUE)
  cat("wrote", args[2], sprintf("(%.0f KB)\n", file.size(args[2]) / 1024))
} else {
  out <- gsub("\r", "", readLines(args[2], warn = FALSE), fixed = TRUE)
  cat(grep("^(R:|check:)", out, value = TRUE), sep = "\n")
  start <- grep("^<<<CSV klanguage_registered.csv", out)
  end <- grep("^CSV>>>", out)
  if (length(start) != 1L || length(end) != 1L || end <= start) stop("no table found in ", args[2])
  got <- out[(start + 1L):(end - 1L)]
  want <- gsub("\r", "", readLines(REPORTED, warn = FALSE), fixed = TRUE)
  if (identical(got, want)) {
    cat("PASS: the table is identical to", REPORTED, "\n")
  } else {
    stop("FAIL: the table differs from ", REPORTED)
  }
}
